// ============================================================
// listener.rs — Global keyboard listener (Windows WH_KEYBOARD_LL)
//
// Uses SetWindowsHookEx(WH_KEYBOARD_LL) directly via the
// windows-sys crate. Runs a proper Win32 message pump (GetMessage)
// on a dedicated OS thread — this is required for the low-level
// keyboard hook to fire correctly.
//
// No admin privileges required for WH_KEYBOARD_LL.
// ============================================================

use log::{error, info};
use std::collections::HashSet;
use std::sync::atomic::{AtomicPtr, Ordering};
use std::sync::mpsc as std_mpsc;
use std::sync::{Mutex, OnceLock};
use tokio::sync::mpsc::UnboundedSender;

use windows_sys::Win32::Foundation::{LPARAM, LRESULT, WPARAM};
use windows_sys::Win32::UI::Input::KeyboardAndMouse::*;
use windows_sys::Win32::UI::WindowsAndMessaging::*;

/// A key event sent from the OS hook into the async trigger engine.
#[derive(Debug, Clone)]
pub enum KeyEvent {
    Char(char),
    Enter,
    Escape,
    Backspace,
    Alt,
    Paste,
    Other,
}

// Thread-local sender — the hook callback is a plain C function pointer,
// so we communicate via a global atomic pointer to our sender.
static SENDER: AtomicPtr<std_mpsc::SyncSender<KeyEvent>> = AtomicPtr::new(std::ptr::null_mut());

// Tracks currently held virtual keys. Low-level Windows hooks can emit
// repeated key-down messages when a key is held; KAI only wants one event per
// physical press so those repeats cannot duplicate captured prompt text.
static PRESSED_KEYS: OnceLock<Mutex<HashSet<u32>>> = OnceLock::new();

use windows_sys::Win32::System::LibraryLoader::GetModuleHandleW;

/// Starts the global keyboard listener.
/// Must be called from a dedicated OS thread (not an async task).
pub fn start_listener(tx: UnboundedSender<KeyEvent>) {
    // Bridge: std SyncSender (used from hook callback) → tokio UnboundedSender
    let (internal_tx, internal_rx) = std_mpsc::sync_channel::<KeyEvent>(256);

    // Store sender pointer for the hook callback
    let boxed = Box::new(internal_tx);
    SENDER.store(Box::into_raw(boxed), Ordering::SeqCst);

    // Bridge thread: relay from std channel → tokio channel
    std::thread::spawn(move || {
        for event in internal_rx {
            if tx.send(event).is_err() {
                break; // Main app shutting down
            }
        }
    });

    unsafe {
        // Force creation of a message queue for this thread
        let mut msg = std::mem::zeroed::<MSG>();
        PeekMessageW(&mut msg, std::ptr::null_mut(), 0, 0, PM_NOREMOVE);

        // Get module instance for current process
        let h_mod = GetModuleHandleW(std::ptr::null());

        // Install the low-level keyboard hook.
        let hook = SetWindowsHookExW(WH_KEYBOARD_LL, Some(keyboard_proc), h_mod, 0);

        if hook == std::ptr::null_mut() {
            error!(
                "Failed to install keyboard hook! Error code: {}",
                windows_sys::Win32::Foundation::GetLastError()
            );
            error!("This should not require admin privileges. Check antivirus.");
            return;
        }

        info!(
            "Keyboard hook installed successfully (handle: {:?}, module: {:?})",
            hook, h_mod
        );

        // Run the Win32 message pump — REQUIRED for WH_KEYBOARD_LL to fire.
        while GetMessageW(&mut msg, std::ptr::null_mut(), 0, 0) > 0 {
            TranslateMessage(&msg);
            DispatchMessageW(&msg);
        }

        UnhookWindowsHookEx(hook);
        info!("Keyboard hook removed");
    }
}

/// Win32 low-level keyboard hook callback.
/// Called by Windows for every keypress, system-wide.
unsafe extern "system" fn keyboard_proc(n_code: i32, w_param: WPARAM, l_param: LPARAM) -> LRESULT {
    // HC_ACTION (0) means we should process the message
    if n_code == HC_ACTION as i32 {
        let msg_type = w_param as u32;
        if msg_type == WM_KEYUP || msg_type == WM_SYSKEYUP {
            let kb = &*(l_param as *const KBDLLHOOKSTRUCT);
            if let Some(keys) = PRESSED_KEYS.get() {
                if let Ok(mut pressed) = keys.lock() {
                    pressed.remove(&kb.vkCode);
                }
            }
        } else if msg_type == WM_KEYDOWN || msg_type == WM_SYSKEYDOWN {
            let kb = &*(l_param as *const KBDLLHOOKSTRUCT);

            // Ignore keyboard events generated by KAI itself. Without this
            // guard, injected responses are fed back into the trigger engine
            // and can cause duplicate or repetitive output.
            if (kb.flags & LLKHF_INJECTED) != 0 || (kb.flags & LLKHF_LOWER_IL_INJECTED) != 0 {
                return CallNextHookEx(std::ptr::null_mut(), n_code, w_param, l_param);
            }

            let pressed = PRESSED_KEYS.get_or_init(|| Mutex::new(HashSet::new()));
            let ctrl_pressed = if let Ok(mut keys) = pressed.lock() {
                // A key-down for a key already in this set is auto-repeat.
                if !keys.insert(kb.vkCode) {
                    return CallNextHookEx(std::ptr::null_mut(), n_code, w_param, l_param);
                }
                keys.contains(&(VK_CONTROL as u32))
                    || keys.contains(&(VK_LCONTROL as u32))
                    || keys.contains(&(VK_RCONTROL as u32))
            } else {
                false
            };

            let vk_code = kb.vkCode;
            let event = vk_to_key_event(vk_code, ctrl_pressed);

            // Send the event (non-blocking — drop if buffer full)
            let sender_ptr = SENDER.load(Ordering::SeqCst);
            if !sender_ptr.is_null() {
                let _ = (*sender_ptr).try_send(event);
            }
        }
    }

    // MUST call next hook in chain — never swallow events
    CallNextHookEx(std::ptr::null_mut(), n_code, w_param, l_param)
}

/// Maps a Windows Virtual Key code to our KeyEvent type.
fn vk_to_key_event(vk: u32, ctrl_pressed: bool) -> KeyEvent {
    // Ctrl+V inserts clipboard text without generating printable key events.
    // Use the hook's own pressed-key state: Windows has not reliably updated
    // GetAsyncKeyState yet while a low-level hook callback is running.
    if ctrl_pressed && vk == b'V' as u32 {
        return KeyEvent::Paste;
    }

    match vk {
        // Alt key (VK_MENU = 0x12, VK_LMENU = 0xA4, VK_RMENU = 0xA5)
        vk if vk == VK_MENU as u32 || vk == VK_LMENU as u32 || vk == VK_RMENU as u32 => {
            KeyEvent::Alt
        }

        // Enter
        vk if vk == VK_RETURN as u32 => KeyEvent::Enter,

        // Escape
        vk if vk == VK_ESCAPE as u32 => KeyEvent::Escape,

        // Backspace
        vk if vk == VK_BACK as u32 => KeyEvent::Backspace,

        _ => translate_printable_key(vk),
    }
}

/// Resolve a key through the active Windows keyboard layout. This preserves
/// Shift/AltGr state and lets international layouts produce their real text.
fn translate_printable_key(vk: u32) -> KeyEvent {
    let mut keyboard_state = [0u8; 256];
    let mut output = [0u16; 8];
    let written = unsafe {
        if GetKeyboardState(keyboard_state.as_mut_ptr()) == 0 {
            return KeyEvent::Other;
        }
        let scan_code = MapVirtualKeyW(vk, MAPVK_VK_TO_VSC);
        ToUnicode(
            vk,
            scan_code,
            keyboard_state.as_ptr(),
            output.as_mut_ptr(),
            output.len() as i32,
            0,
        )
    };

    if written <= 0 {
        return KeyEvent::Other;
    }

    String::from_utf16(&output[..written as usize])
        .ok()
        .and_then(|text| text.chars().next())
        .map(KeyEvent::Char)
        .unwrap_or(KeyEvent::Other)
}

